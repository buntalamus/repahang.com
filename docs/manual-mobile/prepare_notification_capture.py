#!/usr/bin/env python3
"""Prepare documentation captures of the production WebPushCard's visual states.

The actual widget body is reused. The web-only visibility guard is enabled for
VM rendering, and browser permission/subscription responses are fixtures. No OS
prompt, production subscription or notification is created by this harness.
"""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
source=(ROOT/'mobile/lib/widgets/web_push_card.dart').read_text()
widget=source[source.index('class WebPushCard'):].replace('kIsWeb','documentationWebBuild')
preamble=r'''// Generated by docs/manual-mobile/prepare_notification_capture.py.
// Real application widget body; simulated browser states for documentation.
import 'dart:io';
import 'package:flutter/material.dart';
import 'package:flutter/rendering.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:refpahang/theme.dart';
import 'package:refpahang/widgets/common.dart';
const documentationWebBuild = true;
enum WebPushState { unsupported, needsInstall, denied, off, on }
class WebPush {
  static final instance = WebPush();
  WebPushState current = WebPushState.off;
  WebPushState get state => current;
  Future<WebPushState> refresh({bool syncWithServer = false}) async => current;
  Future<String?> enable() async {current = WebPushState.on; return null;}
  Future<void> disable() async {current = WebPushState.off;}
}
'''
tests=r'''
void main() {
  setUpAll(() async {
    final inter = FontLoader('Inter');
    for(final w in [300,400,500,600,700,800]) {
      inter.addFont(rootBundle.load('assets/fonts/Inter-$w.ttf'));
    }
    await inter.load();
    final icons = FontLoader('MaterialIcons');
    icons.addFont(Future.value(ByteData.view(File('/opt/homebrew/share/flutter/bin/cache/artifacts/material_fonts/MaterialIcons-Regular.otf').readAsBytesSync().buffer)));
    await icons.load();
    final symbols=FontLoader('ManualSymbols');
    symbols.addFont(Future.value(ByteData.view(File('/System/Library/Fonts/Supplemental/Arial.ttf').readAsBytesSync().buffer)));
    await symbols.load();
  });
  setUp(() {
    final v=TestWidgetsFlutterBinding.instance.platformDispatcher.views.first;
    v.physicalSize=const Size(1080,2340);v.devicePixelRatio=2.75;
  });
  Future<void> show(WidgetTester tester,WebPushState state) async {
    WebPush.instance.current=state;
    await tester.pumpWidget(MaterialApp(debugShowCheckedModeBanner:false,theme:buildTheme().copyWith(textTheme:buildTheme().textTheme.copyWith(bodyMedium:buildTheme().textTheme.bodyMedium!.copyWith(fontFamilyFallback:const ['ManualSymbols']))),home:Scaffold(body:Center(child:SizedBox(width:360,child:RepaintBoundary(key:const ValueKey('capture'),child:IntrinsicHeight(child:WebPushCard(key:UniqueKey(),showWhenOn:true))))))));
    await tester.pump();await tester.pump(const Duration(milliseconds:300));
  }
  Future<void> capture(WidgetTester tester,String name) async {
    final boundary=tester.renderObject<RenderRepaintBoundary>(find.byKey(const ValueKey('capture')));
    final image=await tester.runAsync(() => boundary.toImage(pixelRatio:3));
    await expectLater(image,matchesGoldenFile('../../output/manual-mobile/screenshots/$name.png'));
    image?.dispose();
  }
  testWidgets('notification activation and active states',(tester) async {
    await show(tester,WebPushState.off);
    expect(find.text('Aktifkan notifikasi'),findsOneWidget);
    expect(find.text('Aktifkan'),findsOneWidget);
    await capture(tester,'notifikasi_aktifkan');
    await tester.tap(find.text('Aktifkan'));
    await tester.pump();await tester.pump(const Duration(milliseconds:300));
    expect(find.text('Notifikasi aktif'),findsOneWidget);
    await capture(tester,'notifikasi_aktif');
  });
  testWidgets('notification blocked and installation states',(tester) async {
    await show(tester,WebPushState.denied);
    expect(find.text('Notifikasi disekat'),findsOneWidget);
    expect(find.text('Aktifkan'),findsNothing);
    await capture(tester,'notifikasi_disekat');
    await show(tester,WebPushState.needsInstall);
    expect(find.text('Pasang ke skrin utama'),findsOneWidget);
    await capture(tester,'notifikasi_perlu_pasang');
  });
}
'''
(ROOT/'mobile/tool/_manual_notification_capture.dart').write_text(preamble+widget+tests)
print('Prepared mobile/tool/_manual_notification_capture.dart')
